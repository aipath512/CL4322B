#!/usr/bin/env node
// Fetch public, versioned C4322B catalogue and generate the 500 FAQ used by Eva.
// No credentials, no Cloudflare writes. Fail closed on unexpected source changes.
import fs from 'node:fs';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
const base='https://raw.githubusercontent.com/aipath512/GPT-ETALON-4322-V10/main/';
const files=['catalog.js','faq-data.js'];
const texts=await Promise.all(files.map(async name=>{
 const r=await fetch(base+name,{headers:{'User-Agent':'eva-kb-sync'}});
 if(!r.ok)throw new Error(name+': HTTP '+r.status);
 return await r.text();
}));
const ctx=vm.createContext(Object.create(null));
vm.runInContext(texts[0]+'\n'+texts[1]+'\n;globalThis.__items=C4322FAQ.items;',ctx,{timeout:5000});
const items=JSON.parse(JSON.stringify(ctx.__items));
if(items.length!==500)throw new Error('Expected exactly 500 FAQ, got '+items.length);
const seen=new Set();
for(const f of items){
 if(!/^FAQ-\d{3}$/.test(f.id)||typeof f.question!=='string'||typeof f.answer!=='string'||!f.question.trim()||!f.answer.trim())
   throw new Error('Invalid FAQ record: '+JSON.stringify(f).slice(0,100));
 if(seen.has(f.id))throw new Error('Duplicate FAQ id: '+f.id);
 seen.add(f.id);
}
const oneLine=s=>String(s).replace(/\s+/g,' ').trim();
const lines=items.map(f=>'[FAQ '+f.id+' / '+oneLine(f.category)+'] Întrebare: '+oneLine(f.question)+' Răspuns: '+oneLine(f.answer)+' Sursă: '+oneLine(f.sourceId||'C4322B general')+'. (Catalog demonstrativ; disponibilitatea și prețurile trebuie confirmate.)');
const sourceHash=createHash('sha256').update(texts.join('\n')).digest('hex');
const output='// AUTOGENERATED by tools/sync-eva-faq.mjs; do not edit.\n'
 +'// Source: aipath512/GPT-ETALON-4322-V10 (catalog.js + faq-data.js).\n'
 +'// Source SHA-256: '+sourceHash+'\n'
 +'export const FAQ_SYNC_LINES = '+JSON.stringify(lines,null,2)+';\n';
const dest=new URL('../functions/api/_faq_sync.js',import.meta.url);
const previous=fs.existsSync(dest)?fs.readFileSync(dest,'utf8'):'';
if(previous===output){console.log('FAQ already current: 500 entries');process.exit(0);}
fs.writeFileSync(dest,output);
console.log('Generated 500 validated FAQs, source hash '+sourceHash);
